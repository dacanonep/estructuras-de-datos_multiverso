public class Punto3D {
    public double x, y, z;
    public String id;
    public int idAnillo; 
    public int idCapa; 

    public Punto3D(double x, double y, double z, String id, int idAnillo, int idCapa) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.id = id;
        this.idAnillo = idAnillo;
        this.idCapa = idCapa;
    }
    
}